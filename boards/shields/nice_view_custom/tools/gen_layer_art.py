"""Generate widgets/layer_art.{c,h} (right-half layer screens) from the tables in layer_art.py.
Run from this directory:  python3 gen_layer_art.py   (also re-renders the preview PNG)."""
import os
import layer_art as L

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'widgets')
icons = list(L.ICONS)
icon_id = {n: i for i, n in enumerate(icons)}


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def key_c(label, kind):
    k = {'key': 'ART_KEY', 'mod': 'ART_MOD', 'none': 'ART_NONE'}[kind]
    if label is None or kind == 'none':
        return f'{{{k}, ART_EMPTY, NULL, 0}}'
    if label.startswith('@') and len(label) > 1:
        return f'{{{k}, ART_ICON, NULL, ART_ICON_{label[1:].upper()}}}'
    if label.startswith('~') and len(label) > 1:
        return f'{{{k}, ART_TINY, {cstr(label[1:])}, 0}}'
    return f'{{{k}, ART_TEXT, {cstr(label)}, 0}}'


def icon_rows(rows):
    return ', '.join('0x%02x' % int(r.replace('#', '1').replace('.', '0'), 2) for r in rows)


h = ['/* Generated by tools/gen_layer_art.py -- edit tools/layer_art.py instead. */', '#pragma once', '',
     '#include <lvgl.h>', '#include <stdbool.h>', '#include <stdint.h>', '',
     'enum art_kind { ART_KEY, ART_MOD, ART_NONE };',
     'enum art_type { ART_EMPTY, ART_TEXT, ART_ICON, ART_TINY };', '',
     'struct art_key {', '    uint8_t kind;', '    uint8_t type;', '    const char *text;', '    uint8_t icon;', '};', '',
     'struct art_layer {', '    const char *name;', '    bool left_hand; // shows the left hand (layers held by a right thumb)',
     '    const char *hint;', '    struct art_key keys[15];', '    struct art_key thumbs[3];', '};', '',
     f'#define ART_LAYER_COUNT {len(L.BY_ID)}',
     '// Indexed by Miryoku layer id. Each screen shows its own hand of the layer.',
     'extern const struct art_layer art_layers_left[ART_LAYER_COUNT];',
     'extern const struct art_layer art_layers_right[ART_LAYER_COUNT];', '',
     '// Draw the key map of a layer into the middle canvas (68x68, before rotation).',
     '// left_screen mirrors the thumb fan (inner thumb on the right, lowest).',
     'void art_draw_keys(lv_obj_t *canvas, const struct art_layer *layer, bool left_screen);',
     '// 3x5 pixel text, centred in [x, x+w). fg=false draws in the background colour.',
     'void art_draw_tiny(lv_obj_t *canvas, int x, int y, int w, const char *s, bool fg);', '']

c = ['/* Generated by tools/gen_layer_art.py -- edit tools/layer_art.py instead. */', '',
     '#include <string.h>', '#include "layer_art.h"', '#include "util.h"', '']
c += ['enum {'] + [f'    ART_ICON_{n.upper()},' for n in icons] + ['};', '']
c += ['// 7x7 icons, one byte per row, bit 6 = leftmost pixel',
      f'static const uint8_t art_icons[{len(icons)}][7] = {{']
c += [f'    {{{icon_rows(L.ICONS[n])}}}, // {n}' for n in icons] + ['};', '']
glyphs = sorted(L.TINY)
c += ['// 3x5 font: rows of 3 bits, bit 2 = leftmost pixel', 'static const struct {', '    char ch;',
      '    uint8_t rows[5];', '} art_tiny[] = {']
for ch in glyphs:
    rows = ', '.join(str(int(r.replace('#', '1').replace('.', '0'), 2)) for r in L.TINY[ch].split(','))
    c.append(f"    {{'{ch}', {{{rows}}}}},")
c += ['};', '']
for tname, table in [('art_layers_left', L.LEFT_BY_ID), ('art_layers_right', L.RIGHT_BY_ID)]:
    c += [f'const struct art_layer {tname}[ART_LAYER_COUNT] = {{']
    for name, held, grid, kinds, thumbs, hint in table:
        keys = ', '.join(key_c(grid[r][col], kinds[r][col]) for r in range(3) for col in range(5))
        th = ', '.join(key_c(t, kd) for t, kd in thumbs)
        c += [f'    {{{cstr(name)}, false, {cstr(hint)},', f'     {{{keys}}},', f'     {{{th}}}}},']
    c += ['};', '']
c += [r'''
static void art_px(lv_obj_t *canvas, int x, int y, bool fg) {
    if (x < 0 || y < 0 || x >= CANVAS_SIZE || y >= CANVAS_SIZE) {
        return;
    }
    lv_draw_buf_t *db = lv_canvas_get_draw_buf(canvas);
    uint8_t *p = (uint8_t *)db->data + y * db->header.stride + x;
    *p = lv_color_luminance(fg ? LVGL_FOREGROUND : LVGL_BACKGROUND);
}

static void art_icon(lv_obj_t *canvas, int x, int y, uint8_t icon, bool fg) {
    for (int r = 0; r < 7; r++) {
        for (int col = 0; col < 7; col++) {
            if (art_icons[icon][r] & BIT(6 - col)) {
                art_px(canvas, x + col, y + r, fg);
            }
        }
    }
}

void art_draw_tiny(lv_obj_t *canvas, int x, int y, int w, const char *s, bool fg) {
    const int len = strlen(s);
    const int x0 = x + (w - (len * 4 - 1)) / 2;
    for (int i = 0; i < len; i++) {
        for (size_t g = 0; g < ARRAY_SIZE(art_tiny); g++) {
            if (art_tiny[g].ch != s[i]) {
                continue;
            }
            for (int r = 0; r < 5; r++) {
                for (int col = 0; col < 3; col++) {
                    if (art_tiny[g].rows[r] & BIT(2 - col)) {
                        art_px(canvas, x0 + i * 4 + col, y + r, fg);
                    }
                }
            }
            break;
        }
    }
}

static void art_key_draw(lv_obj_t *canvas, int x, int y, int w, int h, const struct art_key *k,
                         lv_draw_label_dsc_t *fg_dsc, lv_draw_label_dsc_t *bg_dsc) {
    if (k->kind == ART_NONE) { // key does nothing on this layer: left blank
        return;
    }
    const bool inv = (k->kind == ART_MOD);
    if (inv) {
        fill_fg(canvas, x, y, w, h);
    } else {
        outline_fg(canvas, x, y, w, h, 1);
    }
    switch (k->type) {
    case ART_TEXT:
        canvas_draw_text(canvas, x, y + (h - 8) / 2, w, inv ? bg_dsc : fg_dsc, k->text);
        break;
    case ART_ICON:
        art_icon(canvas, x + (w - 7) / 2, y + (h - 7) / 2, k->icon, !inv);
        break;
    case ART_TINY:
        art_draw_tiny(canvas, x, y + (h - 5) / 2, w, k->text, !inv);
        break;
    default:
        break;
    }
}

void art_draw_keys(lv_obj_t *canvas, const struct art_layer *layer, bool left_screen) {
    lv_draw_label_dsc_t fg_dsc, bg_dsc;
    init_label_dsc(&fg_dsc, LVGL_FOREGROUND, &lv_font_unscii_8, LV_TEXT_ALIGN_CENTER);
    init_label_dsc(&bg_dsc, LVGL_BACKGROUND, &lv_font_unscii_8, LV_TEXT_ALIGN_CENTER);

    for (int r = 0; r < 3; r++) {
        for (int col = 0; col < 5; col++) {
            art_key_draw(canvas, col * 14, 2 + r * 14, 12, 12, &layer->keys[r * 5 + col], &fg_dsc,
                         &bg_dsc);
        }
    }
    // thumbs sit under the inner columns; the inner thumb (the big angled one on a Corne) is lowest
    for (int i = 0; i < 3; i++) {
        if (left_screen) {
            art_key_draw(canvas, 20 + i * 16, 47 + i, 14, 14, &layer->thumbs[i], &fg_dsc, &bg_dsc);
        } else {
            art_key_draw(canvas, i * 16, 49 - i, 14, 14, &layer->thumbs[i], &fg_dsc, &bg_dsc);
        }
    }
}
''']

open(os.path.join(OUT, 'layer_art.h'), 'w').write('\n'.join(h))
open(os.path.join(OUT, 'layer_art.c'), 'w').write('\n'.join(c))
print('wrote', len(icons), 'icons,', len(glyphs), 'tiny glyphs, 2 x', len(L.BY_ID), 'layers')
